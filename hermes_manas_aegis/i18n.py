def t(lang: str, key: str, **kw: str) -> str:
    """Translate `key` for `lang`, falling back to English, then the key.

    Formatting with **kw is best-effort: on failure the unformatted
    text is returned so a bad placeholder never breaks the HUD.
    """
    table = LANGS.get(lang) or LANGS[DEFAULT_LANG]
    text = table.get(key) or LANGS[DEFAULT_LANG].get(key) or key
    try:
        return text.format(**kw)
    except Exception:
        return text


